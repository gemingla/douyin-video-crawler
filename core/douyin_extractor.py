"""抖音专用提取器+下载器 v3（2026 版）

2026 年现状（实测结论 2025-08，香港 IP / 未登录环境）：
  - 分享页 https://www.iesdouyin.com/share/video/{id} 已改为纯 JS 壳，
    不再有服务端渲染的 window._ROUTER_DATA
  - 旧接口 https://www.iesdouyin.com/web/api/v2/aweme/iteminfo/ 返回
    {"status_code":11110,"status_msg":"encrypt_data_miss"}（需要 a_bogus 签名）
  - https://www.iesdouyin.com/aweme/v1/web/aweme/detail/ 直接 403 blocked
  - www.douyin.com/aweme/v1/web/aweme/detail/?aweme_id=... 需 a_bogus + msToken 签名
  - 视频页 /video/{id} 对未登录（或海外 IP）用户可能 404 并重定向到精选页，
    页面自己被替换为推荐流 —— 因此拦截视频页的「媒体请求」会把其它视频拿下！
  - yt-dlp 抖音提取器不生成 a_bogus（源码留 TODO），2026 年已基本失效

【2026 可用方案（本模块主路径）】
  抖音网页版全局 hook 了 window.fetch，会自动为同源请求计算 a_bogus 签名。
  因此只需：
    1. 用一个无头/有头浏览器打开 https://www.douyin.com/（首页 200 即可，
       无需目标视频页可访问，海外 IP 也行）
    2. 在页面上下文中 evaluate「fetch(detail API)」—— 签名由页面 hook 自动补全
    3. 校验返回 aweme_detail.aweme_id == 目标 ID（防错拿）
    4. 用浏览器 Cookie 下载 play_addr / bit_rate 直链

  备用路径（hook 失效时）：
    - 视频页渲染 + 详情 API 拦截（同样必须校验目标 ID）
    - CDP 连接用户已登录的 Chrome/Edge（远程调试端口），复用真实登录态
    - yt-dlp + 用户 Cookie 文件
"""

