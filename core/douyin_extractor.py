def download_douyin_result(
    result: Dict[str, Any],
    output_dir: str,
    filename: str = "抖音视频",
    progress_cb: Optional[Callable] = None,
    cancel_event: Optional[threading.Event] = None,
    quality: str = "best",
    timeout: int = 120000,
) -> str:
    """根据提取结果直接下载（供 GUI 使用）

    Args:
        result: extract_douyin_video 的返回
        output_dir: 输出目录
        filename: 文件名（不含扩展名）
        progress_cb: 回调 (downloaded_bytes, total_bytes, status)
        cancel_event: 取消事件
        quality: 画质档位 "best"/"1080p"/"720p"/"540p"/"360p"

    Returns:
        文件绝对路径
    """
    if _requests is None:
        raise DouyinError("缺少 requests 库")

    urls = _select_urls_by_quality(result, quality)
    if not urls:
        # 图集无视频
        if result.get("images"):
            files = download_douyin_images(
                result, output_dir, filename, progress_cb=progress_cb,
                cancel_event=cancel_event)
            return files[0] if files else ""
        raise DouyinError("没有可用的视频地址")

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    safe_name = re.sub(r'[\x00-\x1f\\/:*?"<>|\r\n#]', '_',
                       str(filename)).strip('._ ') or "douyin_video"
    safe_name = re.sub(r'_+', '_', safe_name)[:80]

    cookies = result.get("cookies") or []
    session = _requests.Session()
    for c in cookies:
        if c.get("name") and c.get("value") is not None:
            session.cookies.set(c["name"], c["value"],
                                domain=c.get("domain", ""),
                                path=c.get("path", "/"))

    headers = {
        "User-Agent": DOUYIN_UA,
        "Referer": REFERER_MAIN,
        "Origin": "https://www.douyin.com",
        "Accept": "video/mp4,video/*;q=0.9,*/*;q=0.8",
        "Accept-Language": "zh-CN,zh;q=0.9",
    }
    if cookies:
        headers["Cookie"] = build_cookie_header(cookies)

    # 探测最优地址
    url, size = _pick_download_url(urls, session, headers,
                                   preferred=urls[0])
    if not url:
        # 最后兜底：GET 试一次
        for u in urls:
            try:
                resp = session.get(u, headers=headers, stream=True, timeout=20)
                if resp.status_code == 200:
                    chunk = next(resp.iter_content(4096))
                    if chunk:
                        url, size = u, int(
                            resp.headers.get("content-length", 0) or 0)
                        break
            except Exception:
                continue
    if not url:
        raise DouyinError("所有候选视频地址均不可用")

    filepath = output_path / f"{safe_name}.mp4"
    counter = 1
    while filepath.exists() or (output_path / f"{safe_name}.mp4.part").exists():
        filepath = output_path / f"{safe_name}_{counter}.mp4"
        counter += 1
    part_file = output_path / (filepath.name + ".part")

    if progress_cb:
        progress_cb(0, size or 0, "start")

    # 断点续传 + 多源重试
    valid_urls = [url] + [u for u in urls if u != url]
    last_err: Optional[str] = None
    done = False
    downloaded = 0
    total = size or 0

    for attempt in range(3):
        for u in valid_urls[:8]:
            if cancel_event and cancel_event.is_set():
                raise DouyinError("下载已取消")
            try:
                offset = part_file.stat().st_size if part_file.exists() else 0
                req_headers = dict(headers)
                if offset > 0:
                    req_headers["Range"] = f"bytes={offset}-"

                resp = session.get(u, headers=req_headers, stream=True,
                                   timeout=timeout, allow_redirects=True)
                if resp.status_code not in (200, 206):
                    continue
                if offset > 0 and resp.status_code == 200:
                    # 服务器不支持断点，重新开始
                    offset = 0
                    if part_file.exists():
                        part_file.unlink()

                mode = "ab" if offset > 0 and resp.status_code == 206 else "wb"
                cur_total = int(
                    resp.headers.get("content-length", 0) or 0)
                if mode == "wb":
                    downloaded = 0
                    total = cur_total or total
                else:
                    downloaded = offset
                    total = offset + (cur_total or 0)
                body_total = total or 0

                with open(part_file, mode) as f:
                    for chunk in resp.iter_content(chunk_size=64 * 1024):
                        if cancel_event and cancel_event.is_set():
                            raise DouyinError("下载已取消")
                        if chunk:
                            f.write(chunk)
                            downloaded += len(chunk)
                            if progress_cb:
                                progress_cb(downloaded, body_total,
                                            "downloading")

                done = True
                break
            except DouyinError:
                raise
            except Exception as e:
                last_err = str(e)
                continue
        if done:
            break
        time.sleep(2)

    if not done:
        if part_file.exists():
            try:
                part_file.unlink()
            except Exception:
                pass
        raise DouyinError(f"下载失败: {last_err or '所有源均不可用'}")

    # 校验并改名为正式文件
    if part_file.stat().st_size == 0:
        part_file.unlink()
        raise DouyinError("文件为空，下载失败")
    try:
        os.replace(part_file, filepath)
    except Exception:
        # 改名失败则保留 part（重试场景）
        pass

    if progress_cb:
        progress_cb(downloaded, total or downloaded, "finished")
    return str(filepath.resolve())


