def _is_video_like_url(u: str) -> bool:
    """判断 URL 是否像视频下载源（排除配乐 mp3 / 静态图 / 封面）"""
    if re.search(r'(\.mp3(\?|$)|\.m4a(\?|$)|/music|ies-music)',
                 u, re.I):
        return False
    if re.search(r'(\.jpg|\.jpeg|\.png|\.webp|\.heic|\.gif)(\?|$)', u, re.I):
        return False
    if re.search(r'(image|cover|avatar|tplv|webpic)', u, re.I) \
            and "aweme/v1/play" not in u:
        return False
    return True


def parse_aweme_detail(detail: dict) -> Optional[Dict[str, Any]]:
    """从 aweme_detail 中解析视频候选地址与元数据"""
    if not detail:
        return None
    video = detail.get("video") or {}

    candidates: List[Tuple[int, str, str]] = []  # (优先级, url, label)
    seen = set()

    def add(priority: int, urls, label: str):
        for u in urls or []:
            u = _clean_url(u)
            if not u or u in seen:
                continue
            seen.add(u)
            # 排除配乐/封面等非视频源
            if not _is_video_like_url(u):
                continue
            candidates.append((priority, u, label))

    play_addr = video.get("play_addr") or {}
    uri = play_addr.get("uri") or ""
    # 图集/纯音频作品的 play_addr.uri 是完整 mp3 链接，不是视频 ID
    if not re.match(r'^v\d', uri or ""):
        uri = ""
    add(0, play_addr.get("url_list"), "play_addr")

    dl_addr = video.get("download_addr") or {}
    add(1, dl_addr.get("url_list"), "download_addr")

    # 不同码率（画质档位）
    bit_rates: Dict[str, List[str]] = {}
    for br in video.get("bit_rate") or []:
        gear = br.get("gear_name") or ""
        urls = (br.get("play_addr") or {}).get("url_list") or []
        if gear:
            bit_rates.setdefault(gear, [])
        add(3, urls, f"bit_rate:{gear}")
        for u in urls:
            u = _clean_url(u)
            if gear and u and _is_video_like_url(u):
                bit_rates.setdefault(gear, [])
                if u not in bit_rates[gear]:
                    bit_rates[gear].append(u)

    # 用 uri 重建官方播放直链（历史接口，仍会 302 到 CDN）
    if uri:
        for q in ("720p", "1080p", "540p", "360p"):
            rebuilt = (f"https://www.douyin.com/aweme/v1/play/"
                       f"?video_id={uri}&ratio={q}&line=0")
            if rebuilt not in seen:
                seen.add(rebuilt)
                candidates.append((2, rebuilt, f"play_rebuilt:{q}"))

    candidates.sort(key=lambda x: x[0])
    urls = [u for _, u, _ in candidates]
    labels = {u: lab for _, u, lab in candidates}

    # 图集
    images: List[str] = []
    for img in detail.get("images") or []:
        iu = (img.get("url_list") or [])
        if iu:
            # url_list 通常从大到小，取最清晰
            images.append(_clean_url(iu[0]))

    # 元数据
    author = detail.get("author") or {}
    statis = detail.get("statistics") or {}
    video_info = detail.get("video") or {}
    cover = ""
    cover_c = video_info.get("cover") or {}
    if cover_c.get("url_list"):
        cover = _clean_url(cover_c["url_list"][-1])
    else:
        dyn = video_info.get("dynamic_cover") or {}
        if dyn.get("url_list"):
            cover = _clean_url(dyn["url_list"][-1])

    duration_ms = video_info.get("duration") or 0
    duration = duration_ms / 1000.0 if duration_ms else 0

    return {
        "video_id": str(detail.get("aweme_id") or ""),
        "urls": urls,
        "labels": labels,
        "bit_rates": bit_rates,
        "uri": uri,
        "images": images,
        "height": video_info.get("height") or 0,
        "width": video_info.get("width") or 0,
        "duration": duration,
        "title": (detail.get("desc") or "").strip(),
        "uploader": author.get("nickname") or "",
        "uploader_id": author.get("uid") or "",
        "cover": cover,
        "digg_count": statis.get("digg_count") or 0,
        "comment_count": statis.get("comment_count") or 0,
        "share_count": statis.get("share_count") or 0,
        "collect_count": statis.get("collect_count") or 0,
        "play_count": statis.get("play_count") or 0,
        "is_note": bool(detail.get("images")) and not urls,
    }


def parse_quality_rank(gear: str) -> int:
    """从 gear_name 解析画质档位排序（数字越大越好）"""
    g = (gear or "").lower()
    for i, kw in enumerate(("1080", "720", "540", "360")):
        if kw in g:
            base = 4 - i
            if "normal" in g or "higher" in g:
                return base * 10 + 2
            if "high" in g:
                return base * 10 + 1
            return base * 10
    return 0


def collect_from_api_json(payload: dict,
                          target_id: Optional[str] = None
                          ) -> List[Dict[str, Any]]:
    """从 detail 响应收集 aweme 数据（可过滤目标 ID）"""
    results = []
    for key in ("aweme_detail", "aweme_list", "item_list"):
        v = payload.get(key)
        if isinstance(v, list):
            results.extend(v)
        elif isinstance(v, dict) and v.get("aweme_id"):
            results.append(v)
    if target_id:
        results = [d for d in results if str(d.get("aweme_id") or "") == str(target_id)]
    return results


