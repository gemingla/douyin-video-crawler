# ── 小工具 ────────────────────────────────────────────────────
def _clean_url(u: str) -> str:
    u = (u or "").strip()
    u = u.replace("\\u0026", "&").replace("\u0026", "&")
    u = u.replace("\\/", "/")
    if u.startswith("http://"):
        u = "https://" + u[7:]
    return u


def _random_token(n: int = 107) -> str:
    """生成 msToken 风格的随机串"""
    return "".join(random.choices(
        string.ascii_letters + string.digits + "-_", k=n))


def extract_video_id(url: str) -> Optional[str]:
    """从 URL 中提取 aweme_id（数字），失败返回 None"""
    m = re.search(r'(?:share/video|video|note|slide)/(\d{14,22})', url)
    if m:
        return m.group(1)
    m = re.search(r'(?:aweme_id|item_ids)=(\d{14,22})', url)
    if m:
        return m.group(1)
    return None


def resolve_share_url(url: str, timeout: int = 15) -> Tuple[str, Optional[str]]:
    """跟随重定向解析分享短链。

    Returns:
        (最终页面URL, aweme_id)
    """
    if _requests is None:
        raise DouyinError("缺少 requests 库")
    # 已经是标准页面链接
    if re.search(r'douyin\.com/(video|note|slide)/\d+', url) \
            and "v.douyin" not in url:
        return url, extract_video_id(url)

    headers = {
        "User-Agent": DOUYIN_UA,
        "Referer": REFERER_SHARE,
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "zh-CN,zh;q=0.9",
    }
    try:
        resp = _requests.get(url, headers=headers, allow_redirects=True,
                             timeout=timeout)
        final = resp.url
    except Exception as e:
        raise DouyinError(f"短链解析失败: {e}")
    if not final or final == url:
        final = url
    return final, extract_video_id(final)


# ── Cookie 工具 ───────────────────────────────────────────────
def cookies_to_requests(cookies: List[dict]) -> Dict[str, str]:
    """Playwright cookie 列表 -> requests cookies dict"""
    out = {}
    for c in cookies or []:
        name, value = c.get("name"), c.get("value")
        if name and value is not None:
            out[name] = value
    return out


def save_cookies_netscape(cookies: List[dict], filepath: str,
                          domain_filter: str = "douyin") -> Optional[str]:
    """Playwright cookie 列表 -> Netscape 格式 cookie 文件（yt-dlp 可用）"""
    try:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# Generated by VideoCrawler v3\n\n")
            for c in cookies or []:
                domain = c.get("domain", "")
                if domain_filter and domain_filter not in domain:
                    continue
                name, value = c.get("name", ""), c.get("value", "")
                path = c.get("path", "/")
                has_dot = domain.startswith(".")
                dspec = "TRUE" if has_dot else "FALSE"
                secure = "TRUE" if c.get("secure") else "FALSE"
                expires = c.get("expires") or 0
                expires = 0 if expires <= 0 else int(expires)
                f.write(f"{domain}\t{dspec}\t{path}\t{secure}\t"
                        f"{expires}\t{name}\t{value}\n")
        return filepath if os.path.getsize(filepath) > 50 else None
    except Exception:
        return None


def load_cookies_from_netscape(filepath: str) -> List[dict]:
    """解析 Netscape cookie 文件 -> Playwright cookie 列表"""
    cookies = []
    try:
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) < 7:
                    continue
                domain, _, path, secure, expires, name, value = parts[:7]
                cookies.append({
                    "name": name,
                    "value": value,
                    "domain": domain,
                    "path": path or "/",
                    "secure": secure.lower() == "true",
                    "expires": float(expires) if expires else 0,
                    "httpOnly": False,
                })
    except Exception:
        pass
    return cookies


def build_cookie_header(cookies: List[dict]) -> str:
    return "; ".join(f"{c['name']}={c['value']}"
                     for c in cookies or []
                     if c.get("name") and c.get("value") is not None)


def _temp_cookie_file(cookies: List[dict]) -> Optional[str]:
    if not cookies:
        return None
    path = os.path.join(tempfile.gettempdir(),
                        f"vc_douyin_{int(time.time())}.txt")
    return save_cookies_netscape(cookies, path)


